function getCurrentLanguage() {
    return localStorage.getItem(LANG_KEY) || "hy";
}

function changeLanguage(language) {
    if (!translations[language]) {
        language = "hy";
    }

    localStorage.setItem(LANG_KEY, language);
    document.documentElement.lang = language;

    updateLanguageButtons();
    translatePage();

    if (typeof loadProducts === "function") {
        loadProducts();
    }

    if (typeof loadFavorites === "function") {
        loadFavorites();
    }

    if (typeof loadCart === "function") {
        loadCart();
    }
}

function updateLanguageButtons() {
    const language = getCurrentLanguage();

    const hy = document.getElementById("lang-hy");
    const en = document.getElementById("lang-en");
    const ru = document.getElementById("lang-ru");

    if (hy) hy.style.opacity = language === "hy" ? "1" : "0.5";
    if (en) en.style.opacity = language === "en" ? "1" : "0.5";
    if (ru) ru.style.opacity = language === "ru" ? "1" : "0.5";
}

function translateText(text) {
    if (!text) return text;

    const language = getCurrentLanguage();
    const dictionary = translations[language];

    let result = text;

    Object.keys(dictionary).forEach(function (key) {
        if (result.includes(key)) {
            result = result.split(key).join(dictionary[key]);
        }
    });

    return result;
}

function translatePage() {
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT
    );

    const nodes = [];

    while (walker.nextNode()) {
        const node = walker.currentNode;

        if (
            node.parentElement &&
            !["SCRIPT", "STYLE"].includes(node.parentElement.tagName)
        ) {
            nodes.push(node);
        }
    }

    nodes.forEach(function (node) {
        if (node.nodeValue.trim()) {
            node.nodeValue = translateText(node.nodeValue);
        }
    });

    document.querySelectorAll("input, textarea").forEach(function (element) {
        if (element.placeholder) {
            element.placeholder = translateText(element.placeholder);
        }
    });

    updateLanguageButtons();
}

document.addEventListener("DOMContentLoaded", function () {
    document.documentElement.lang = getCurrentLanguage();

    setTimeout(function () {
        translatePage();
    }, 100);

    updateLanguageButtons();
});
